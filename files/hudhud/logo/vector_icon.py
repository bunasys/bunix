"""The hoopoe as a Chromium vector icon, for Hudhud's Shields button:

    python3 -I vector_icon.py

Reads hudhud-mono.svg (an output of build.py) and writes hoopoe_icon.cc
beside the button's code (files/hudhud/chromium/chrome/browser/ui/views/
hudhud_shields), in Chromium's vector-icon commands (ui/gfx/
vector_icon_types.h).  Run it again whenever the mark changes; nothing
else needs to.
"""
import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, 'hudhud-mono.svg')
OUTPUT = os.path.join(HERE, '..', 'chromium', 'chrome', 'browser', 'ui', 'views',
                      'hudhud_shields', 'hoopoe_icon.cc')

# Toolbar icons are drawn on a 20 dip canvas with a little air around the
# glyph; the ring is 17 dip across, like Chromium's own round icons.
CANVAS = 20
RING_DIAMETER = 17

# The SVG's curl is traced with a point every unit of its 1024 grid: far more
# than 20 dip need.  Points closer than this to the simplified outline are
# dropped (in SVG units: 1 of 1024 is a thirtieth of a dip).
TOLERANCE = 1.0

# The ring's geometry (README.md): centre and outer and inner wall radii
RING_CENTRE = (512.0, 512.0)
RING_OUTER = 248.0
RING_INNER = 152.0


def simplify(points, tolerance):
    """Ramer-Douglas-Peucker: the fewest points that keep the outline within
    `tolerance` of the original."""
    if len(points) < 3:
        return points
    first, last = points[0], points[-1]
    dx, dy = last[0] - first[0], last[1] - first[1]
    length = math.hypot(dx, dy) or 1e-9
    farthest, distance = 0, 0.0
    for i in range(1, len(points) - 1):
        d = abs(dy * (points[i][0] - first[0]) - dx * (points[i][1] - first[1])) / length
        if d > distance:
            farthest, distance = i, d
    if distance <= tolerance:
        return [first, last]
    return simplify(points[:farthest + 1], tolerance)[:-1] + simplify(points[farthest:], tolerance)


def number(value):
    """A coordinate as the .icon files write it: 4, 4.5f."""
    value = round(value, 2)
    if value == int(value):
        return str(int(value))
    return ('%.2f' % value).rstrip('0') + 'f'


def main():
    svg = open(SOURCE, encoding='utf-8').read()
    paths = re.findall(r'<path d="([^"]*)"', svg)
    # The first path is the ring, two circles; the others are the curl and the
    # two fillets that join it to the ring, each a polygon
    polygons = [[(float(x), float(y)) for x, y in re.findall(r'[ML] ([\d.]+) ([\d.]+)', d)]
                for d in paths[1:]]

    scale = RING_DIAMETER / (2 * RING_OUTER)

    def dip(x, y):
        return (number((x - RING_CENTRE[0]) * scale + CANVAS / 2),
                number((y - RING_CENTRE[1]) * scale + CANVAS / 2))

    centre_x, centre_y = dip(*RING_CENTRE)
    lines = [
        'CANVAS_DIMENSIONS, %d,' % CANVAS,
        # one path, filled even-odd (the default): the inner circle is the hole
        'CIRCLE, %s, %s, %s,' % (centre_x, centre_y, number(RING_OUTER * scale)),
        'CIRCLE, %s, %s, %s,' % (centre_x, centre_y, number(RING_INNER * scale)),
    ]
    for polygon in polygons:
        polygon = simplify(polygon, TOLERANCE)
        # a path of its own: it overlaps the ring, which even-odd in one path
        # would cut out
        lines.append('NEW_PATH,')
        lines.append('MOVE_TO, %s, %s,' % dip(*polygon[0]))
        for point in polygon[1:]:
            lines.append('LINE_TO, %s, %s,' % dip(*point))
        lines.append('CLOSE,')

    commands = ''.join('    ' + line + '\n' for line in lines)
    with open(OUTPUT, 'w', encoding='utf-8') as output:
        output.write(f'''// Generated by files/hudhud/logo/vector_icon.py from hudhud-mono.svg:
// edit and run that, not this.

#include "chrome/browser/ui/views/hudhud_shields/hoopoe_icon.h"

#include <iterator>

#include "ui/gfx/vector_icon_types.h"

namespace hudhud_shields {{

namespace {{

using gfx::CANVAS_DIMENSIONS;
using gfx::CIRCLE;
using gfx::CLOSE;
using gfx::LINE_TO;
using gfx::MOVE_TO;
using gfx::NEW_PATH;

constexpr gfx::PathElement kHoopoePath[] = {{
{commands}}};

constexpr gfx::VectorIconRep kHoopoeReps[] = {{{{kHoopoePath}}}};

}}  // namespace

constexpr gfx::VectorIcon kHoopoeIcon = {{kHoopoeReps, std::size(kHoopoeReps),
                                         "hudhud_hoopoe"}};

}}  // namespace hudhud_shields
''')
    print(OUTPUT)


main()
